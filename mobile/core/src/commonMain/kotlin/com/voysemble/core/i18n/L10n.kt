// The phones' user-facing text in the two languages the product supports (slice 039). One key
// per string (`Txt`), one table per language (Tables.kt), one lookup (`tr`). The language is set
// once at launch from the device (`AppLocale.set`) and read by every screen and view model on
// Android and iOS, so the two apps say the same thing and a missing Korean line is a test
// failure, not a surprise. Placeholders are `{0}`, `{1}`, ... in both tables.

package com.voysemble.core.i18n

/** The app's language: "ko" or "en". The device language decides at launch; tests set it. */
public object AppLocale {
    public var current: String = "en"

    /** Accepts any language tag ("ko-KR", "ko", "en-US"); anything but Korean is English. */
    public fun of(languageTag: String): String = if (languageTag.lowercase().startsWith("ko")) "ko" else "en"

    public fun set(languageTag: String) {
        current = of(languageTag)
    }

    public val isKorean: Boolean get() = current == "ko"
}

/** The text in the current language; English when a table has no line (the test forbids that). */
public fun tr(id: Txt): String = (if (AppLocale.isKorean) KO else EN)[id] ?: EN.getValue(id)

/** `tr` with `{0}`, `{1}`, ... replaced in order; a null argument prints as an empty string. */
public fun trf(id: Txt, vararg args: Any?): String {
    var out = tr(id)
    args.forEachIndexed { i, a -> out = out.replace("{$i}", a?.toString() ?: "") }
    return out
}

/* Swift cannot pass a Kotlin vararg comfortably; these three cover every template in the tables. */
public fun tr1(id: Txt, a: Any?): String = trf(id, a)
public fun tr2(id: Txt, a: Any?, b: Any?): String = trf(id, a, b)
public fun tr3(id: Txt, a: Any?, b: Any?, c: Any?): String = trf(id, a, b, c)
public fun tr4(id: Txt, a: Any?, b: Any?, c: Any?, d: Any?): String = trf(id, a, b, c, d)

/** How many `{n}` placeholders a line has; the test checks both tables agree per key. */
public fun placeholderCount(line: String): Int = Regex("\\{(\\d+)}").findAll(line).count()

